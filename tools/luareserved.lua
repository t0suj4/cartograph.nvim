-- luareserved — distil, PER LUA VERSION, which words cannot be an identifier, by ASKING THE INTERPRETERS (CART-1012).
--
--   nvim --headless -u NONE -l tools/luareserved.lua           -- rewrite the artifact
--   nvim --headless -u NONE -l tools/luareserved.lua --check   -- re-distil and diff, write nothing (exit 1 on drift)
--
-- ★★★ USER CONDITION (CART-1012, 2026-11-07): "I guess we need version sensitive reserved word list" — reserved words
-- are LANGUAGE AND VERSION-SENSITIVE, NOT an unconditional per-language blacklist. So nothing here is authored:
--   · CANDIDATES are the tree-sitter Lua grammar's word-shaped symbols, named and anonymous, each split on `_`
--     (`break_statement` → `break`: the grammar spells `break`/`nil`/`true`/`false` as NAMED nodes) — an
--     over-approximation on purpose, because
--   · THE ORACLE is each installed interpreter, asked `local W = 1` for every candidate: a refusal is a reserved word.
--     `chunk`, `comment`, `statement` pass and drop out by themselves.
-- The artifact stamps each interpreter's `-v` line and the candidate set's hash, so a stale artifact is detectable
-- (tests/luareserved_spec.lua re-distils when the interpreters are present).
--
-- ⚠ WHAT IT DOES NOT HAVE: a version with no interpreter on this machine (5.2, 5.3, 5.5 on 2026-11-07) has NO entry,
-- and that absence is the honest answer — the guard says "undistilled" rather than guessing that 5.2 ⊂ 5.4.
-- Adding one = install the interpreter and add a row to INTERPS.

local REPO = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h')
local OUT = REPO .. '/lua/cartograph/spec/luareserved.lua'
-- version key (the profile's `lua_version`, '%.1f') -> the interpreter that answers for it
local INTERPS = { { key = '5.1', bin = 'lua5.1' }, { key = '5.4', bin = 'lua5.4' }, { key = 'luajit', bin = 'luajit' } }

local function candidates()
    local seen, out = {}, {}
    for sym in pairs(vim.treesitter.language.inspect('lua').symbols) do
        local s = sym:match('^"(.*)"$') or sym
        for w in s:gmatch('[%a_][%w_]*') do
            for part in w:gmatch('[^_]+') do
                if not seen[part] and part:match('^%a%w*$') then seen[part] = true; out[#out + 1] = part end
            end
        end
    end
    table.sort(out)
    return out
end

local function sh(cmd, input)
    local r = vim.system(cmd, { stdin = input, text = true }):wait()
    return r.code, (r.stdout or '') .. (r.stderr or '')
end

local function distil()
    local cand = candidates()
    local res = { candidates = #cand, candidates_sha = vim.fn.sha256(table.concat(cand, ' ')), versions = {} }
    for _, it in ipairs(INTERPS) do
        if vim.fn.executable(it.bin) == 1 then
            local _, ver = sh({ it.bin, '-v' })
            local words = {}
            for _, w in ipairs(cand) do
                local code = sh({ it.bin, '-' }, ('local %s = 1\n'):format(w))
                if code ~= 0 then words[#words + 1] = w end
            end
            res.versions[it.key] = { interpreter = vim.trim(ver:match('[^\n]*')), words = words }
        end
    end
    return res
end

local function render(r)
    local keys = vim.tbl_keys(r.versions)
    table.sort(keys)
    local L = {
        '-- GENERATED by tools/luareserved.lua (CART-1012) — do not edit; re-run the tool. Which words each Lua version',
        '-- refuses as an identifier, asked of that version\'s interpreter. A version absent here is UNDISTILLED, not',
        '-- "reserves nothing": planguards\' parses guard makes no claim for it.',
        'return {',
        ('    candidates = %d, -- word-shaped tree-sitter Lua grammar symbols, split on _'):format(r.candidates),
        ('    candidates_sha = %q,'):format(r.candidates_sha),
        '    versions = {',
    }
    for _, k in ipairs(keys) do
        local v = r.versions[k]
        local q = {}
        for i, w in ipairs(v.words) do q[i] = ('%q'):format(w) end
        L[#L + 1] = ('        [%q] = { interpreter = %q,'):format(k, v.interpreter)
        L[#L + 1] = ('            words = { %s } },'):format(table.concat(q, ', '))
    end
    L[#L + 1] = '    },'
    L[#L + 1] = '}'
    return table.concat(L, '\n') .. '\n'
end

local text = render(distil())
if vim.tbl_contains(_G.arg or {}, '--check') then
    local f = io.open(OUT, 'r')
    local cur = f and f:read('*a') or ''
    if f then f:close() end
    if cur == text then print('luareserved: artifact is current') return end
    io.stdout:write(vim.diff(cur, text) or '')
    print('luareserved: DRIFT — re-run without --check')
    os.exit(1)
end
local f = assert(io.open(OUT, 'w'))
f:write(text)
f:close()
print('luareserved: wrote ' .. OUT)
